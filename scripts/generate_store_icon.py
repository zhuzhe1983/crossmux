#!/usr/bin/env python3
"""Embed the versioned CrossStore CSI1 icon; no image libraries needed to build."""
from pathlib import Path

if 'Import' in globals():
    Import('env')  # noqa: F821
    ROOT = Path(env.subst('$PROJECT_DIR'))  # noqa: F821
else:
    ROOT = Path(__file__).resolve().parents[1]


def generate():
    bundle = (ROOT / 'assets/app-icons/appstore/icon.csi').read_bytes()
    if len(bundle) != 7048 or bundle[:8] != b'CSI1\0\0\0\0':
        raise ValueError('Invalid built-in CrossStore icon bundle')
    lines = ['// Generated by scripts/generate_store_icon.py; do not edit.',
             '#pragma once', '#include <cstdint>', 'namespace crossstore::builtin {',
             'inline constexpr uint8_t STORE_ICON[] = {']
    lines += ['  ' + ', '.join(f'0x{value:02x}' for value in bundle[i:i + 16]) + ','
              for i in range(0, len(bundle), 16)]
    lines += ['};', '}  // namespace crossstore::builtin', '']
    output = ROOT / 'src/crossstore/StoreIcon.generated.h'
    content = '\n'.join(lines)
    if not output.exists() or output.read_text() != content:
        output.write_text(content)


if __name__ == '__main__' or 'Import' in globals():
    generate()
