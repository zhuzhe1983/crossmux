#!/usr/bin/env python3
"""Create an original damped wooden-percussion cue, WAV and Flash PCM table.

No downloaded samples, resampling, or time stretching. The WAV and firmware
contain the same 24 kHz, 16-bit mono frames at their original duration/pitch.
"""
from pathlib import Path
import math
import io
import random
import struct
import wave

if 'Import' in globals():
    Import('env')  # noqa: F821
    ROOT = Path(env.subst('$PROJECT_DIR'))  # noqa: F821
else:
    ROOT = Path(__file__).resolve().parents[1]
RATE = 24000
FRAMES = 3360  # 140 ms


def generate():
    rng = random.Random(2048)
    # Inharmonic shell resonances; a brief filtered contact transient supplies
    # the mallet attack. No sustained square wave or musical note sequence.
    modes = ((782, 1.0, .028), (1198, .47, .019), (1913, .24, .012), (2841, .10, .007))
    raw = []
    noise = 0.0
    for i in range(FRAMES):
        t = i / RATE
        noise = .35 * noise + .65 * rng.uniform(-1, 1)
        body = sum(gain * math.sin(2 * math.pi * hz * t) * math.exp(-t / decay)
                   for hz, gain, decay in modes)
        attack = 1 - math.exp(-t / .0003)
        tail = min(1, (FRAMES - 1 - i) / (RATE * .012))
        raw.append((body + .22 * noise * math.exp(-t / .0017)) * attack * tail)
    mean = sum(raw) / len(raw)
    # Window the tiny DC correction so both endpoints remain exactly zero.
    window = [math.sin(math.pi * i / (FRAMES - 1)) ** 2 for i in range(FRAMES)]
    correction = mean * FRAMES / sum(window)
    raw = [value - correction * win for value, win in zip(raw, window)]
    gain = .65 * 32767 / max(abs(value) for value in raw)
    pcm = [round(value * gain) for value in raw]
    folder = ROOT / 'assets/audio'
    folder.mkdir(parents=True, exist_ok=True)
    wav_bytes = io.BytesIO()
    with wave.open(wav_bytes, 'wb') as output:
        output.setnchannels(1)
        output.setsampwidth(2)
        output.setframerate(RATE)
        output.writeframes(struct.pack('<' + 'h' * len(pcm), *pcm))
    wav_path = folder / 'woodfish.wav'
    if not wav_path.exists() or wav_path.read_bytes() != wav_bytes.getvalue():
        wav_path.write_bytes(wav_bytes.getvalue())
    lines = ['// Generated by scripts/generate_woodfish_audio.py; do not edit.',
             '#pragma once', '#include <cstdint>', 'namespace woodfishAudio {',
             'inline constexpr int16_t SAMPLES[] = {']
    lines += ['  ' + ', '.join(str(v) for v in pcm[i:i+16]) + ',' for i in range(0, len(pcm), 16)]
    lines += ['};', '}  // namespace woodfishAudio', '']
    header = ROOT / 'lib/hal/WoodfishAudio.generated.h'
    content = '\n'.join(lines)
    if not header.exists() or header.read_text() != content:
        header.write_text(content)
    print(f'{len(pcm)} frames, {len(pcm)/RATE:.3f}s, peak {max(abs(v) for v in pcm)}, mean {sum(pcm)/len(pcm):.3f}')


if __name__ == '__main__' or 'Import' in globals():
    generate()
